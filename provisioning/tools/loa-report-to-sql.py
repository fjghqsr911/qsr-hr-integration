"""Convert the UKG People Analytics "QSR Detail LOA History with prompts" export (.xlsx) into a SQL script that loads
leave periods into the hub with stage.usp_import_leave_periods (23-leave-periods.sql).

Only three columns are read: EEID (the employee number), Status Start Date and Status Stop Date. Names, supervisor,
job, location and the LOA reason are never read, so the generated script holds employee numbers and dates only.

Usage (run the generated file in the Azure portal Query editor on sqldb-hrint):
    python -I loa-report-to-sql.py "QSR Detail LOA History with prompts.xlsx" loa-import.sql
    python -I loa-report-to-sql.py report.xlsx loa-check.sql --dry-run      # reconciliation: compare only, write nothing
    python -I loa-report-to-sql.py report.xlsx loa-import.sql --no-rebuild  # load without rebuilding events

Run the report with LOA Start Date from Jan 2020 (or earlier) to today, so leaves running at the Aug 2023 UKG go-live
are included. Needs openpyxl (pip install openpyxl).
"""
import argparse
import datetime as dt
import json
import sys

COLUMNS = {"number": "EEID", "start": "Status Start Date", "stop": "Status Stop Date"}


def as_date(v):
    if v is None or v == "":
        return None
    if isinstance(v, dt.datetime):
        return v.date().isoformat()
    if isinstance(v, dt.date):
        return v.isoformat()
    s = str(v).strip()
    for fmt in ("%Y-%m-%d", "%m/%d/%Y", "%Y-%m-%d %H:%M:%S"):
        try:
            return dt.datetime.strptime(s, fmt).date().isoformat()
        except ValueError:
            pass
    raise ValueError(f"not a date: {s!r}")


def read_periods(path):
    try:
        import openpyxl
    except ImportError:
        sys.exit("openpyxl is not installed: pip install openpyxl")
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    ws = wb.worksheets[0]
    rows = ws.iter_rows(values_only=True)
    header = [str(h or "").strip() for h in next(rows)]
    try:
        idx = {k: header.index(name) for k, name in COLUMNS.items()}
    except ValueError:
        sys.exit(f"expected columns {list(COLUMNS.values())}; found {header}")
    periods, seen, skipped = [], set(), 0
    for r in rows:
        number = str(r[idx["number"]] or "").strip()
        start = as_date(r[idx["start"]]) if number else None
        if not number or not start:
            skipped += 1
            continue
        stop = as_date(r[idx["stop"]])
        key = (number, start, stop)
        if key in seen:              # the report repeats some rows (join fan-out)
            continue
        seen.add(key)
        periods.append({"n": number, "s": start, "e": stop})
    wb.close()
    return periods, skipped


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("xlsx")
    ap.add_argument("out_sql")
    ap.add_argument("--dry-run", action="store_true", help="compare with the hub only (reconciliation); writes nothing")
    ap.add_argument("--no-rebuild", action="store_true", help="do not rebuild events for changed employees")
    a = ap.parse_args()

    periods, skipped = read_periods(a.xlsx)
    if not periods:
        sys.exit("no leave periods found")
    payload = json.dumps(periods, separators=(",", ":")).replace("'", "''")
    starts = sorted(p["s"] for p in periods)
    open_now = sum(1 for p in periods if p["e"] is None)
    with open(a.out_sql, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"-- Leave periods from the UKG LOA History report: {len(periods)} periods, {starts[0]} to {starts[-1]}.\n")
        f.write("-- Employee numbers and dates only. Generated by provisioning/tools/loa-report-to-sql.py.\n")
        f.write("-- Run in the Azure portal Query editor on sqldb-hrint after 23-leave-periods.sql.\n")
        f.write(f"EXEC stage.usp_import_leave_periods @dry_run = {1 if a.dry_run else 0}, "
                f"@rebuild = {0 if a.no_rebuild else 1},\n    @rows = N'{payload}';\n")
    print(f"{len(periods)} periods ({open_now} still on leave), {skipped} blank rows skipped, "
          f"starts {starts[0]} to {starts[-1]} -> {a.out_sql}"
          f"{' (dry run)' if a.dry_run else ''}")


if __name__ == "__main__":
    main()
